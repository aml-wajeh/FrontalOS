"""
AI endpoints. Every response includes `inference_mode: "live" | "demo"` so
the frontend can visibly badge demo results — this is a hard requirement,
not a nice-to-have (see core/ai/tabular_service.py and
core/ai/imaging_service.py for what each mode actually does).
"""
from fastapi import APIRouter, Depends, File, HTTPException, UploadFile
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from core.ai.tabular_service import tabular_service, TabularModelError, FEATURE_COUNT
from core.ai.imaging_service import imaging_service, ImagingModelError
from database.session import get_db
from database.models import Patient, AIPrediction
from api.v1.notifications import create_notification

router = APIRouter(prefix="/ai", tags=["AI Models"])


def _notify_new_prediction(db: Session, patient: Patient, model_label: str) -> None:
    """Fires the NotificationsBell entry the integration task asks for:
    'Notifications generated by backend events (e.g. a new AIPrediction)
    appear in the NotificationsBell'. Notifies the guardian and, if set,
    the assigned doctor — whichever ids exist on the patient row. Never
    raises: a notification failure must not turn a successful prediction
    into a 500 for the caller."""
    try:
        for user_id in {patient.guardian_id, patient.doctor_id}:
            if user_id:
                create_notification(
                    db,
                    user_id=user_id,
                    title="New AI assessment ready",
                    message=f"A new {model_label} result is available for {patient.name}.",
                )
    except Exception:  # noqa: BLE001 — best-effort, never blocks the prediction response
        db.rollback()


class TabularPredictRequest(BaseModel):
    patient_id: int
    features: list[float] = Field(..., description=f"Exactly {FEATURE_COUNT} PCA-transformed features")


def _get_patient_or_404(db: Session, patient_id: int) -> Patient:
    patient = db.query(Patient).filter(Patient.id == patient_id).first()
    if patient is None:
        raise HTTPException(status_code=404, detail=f"Patient {patient_id} not found")
    return patient


@router.post("/tabular")
def predict_tabular(req: TabularPredictRequest, db: Session = Depends(get_db)):
    patient = _get_patient_or_404(db, req.patient_id)

    try:
        result = tabular_service.predict(req.features)
    except TabularModelError as e:
        raise HTTPException(status_code=400, detail=str(e))

    risk_level = "High" if result["probability"] > 0.5 else "Low"

    row = AIPrediction(
        patient_id=req.patient_id,
        model_type="tabular",
        prediction_result={
            "prediction": result["prediction"],
            "probability": result["probability"],
            "probabilities": result["probabilities"],
            "risk_level": risk_level,
            "inference_mode": result["inference_mode"],
            **({"demo_note": result["demo_note"]} if "demo_note" in result else {}),
        },
        confidence=result["confidence"],
    )
    db.add(row)
    db.commit()
    db.refresh(row)
    _notify_new_prediction(db, patient, "tabular ADHD risk")

    return {
        "status": "success",
        "prediction_id": row.id,
        "model": "XGBoost Tabular Clinical Decision Support",
        "prediction": result["prediction"],
        "probability": result["probability"],
        "risk_level": risk_level,
        "confidence": result["confidence"],
        "inference_mode": result["inference_mode"],
        **({"demo_note": result["demo_note"]} if "demo_note" in result else {}),
    }


@router.post("/mri")
async def predict_mri(patient_id: int, file: UploadFile = File(...), db: Session = Depends(get_db)):
    patient = _get_patient_or_404(db, patient_id)

    contents = await file.read()
    if not contents:
        raise HTTPException(status_code=400, detail="Uploaded file is empty")

    try:
        # BUG FIX (staff audit follow-up): imaging_service now supports a
        # sex-conditional model choice (docs/MODELS_README.md §1) — pass
        # the patient's already-recorded gender through so it's used
        # automatically when the female-specific weight file is present,
        # instead of every prediction silently using only the general model.
        result = imaging_service.predict(file.filename or "upload", contents, gender=patient.gender)
    except ImagingModelError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:  # noqa: BLE001 — decode/processing failures -> 400, not a 500 crash
        raise HTTPException(status_code=400, detail=f"Could not process uploaded scan: {e}")

    row = AIPrediction(
        patient_id=patient_id,
        model_type="mri",
        prediction_result={
            "adhd_probability_pct": result["adhd_probability_pct"],
            "findings": result["findings"],
            "inference_mode": result["inference_mode"],
            "model_variant": result.get("model_variant"),
            "filename": file.filename,
            **({"demo_note": result["demo_note"]} if "demo_note" in result else {}),
        },
        confidence=result["adhd_probability_pct"] / 100.0,
    )
    db.add(row)
    db.commit()
    db.refresh(row)
    _notify_new_prediction(db, patient, "MRI scan")

    return {
        "status": "success",
        "prediction_id": row.id,
        "model": "Keras CNN Brain Imaging Analysis",
        "filename": file.filename,
        "slice_image_base64": result["slice_image_base64"],
        "heatmap_image_base64": result["heatmap_image_base64"],
        "adhd_probability_pct": result["adhd_probability_pct"],
        "findings": result["findings"],
        "inference_mode": result["inference_mode"],
        "model_variant": result.get("model_variant"),
        **({"demo_note": result["demo_note"]} if "demo_note" in result else {}),
    }
